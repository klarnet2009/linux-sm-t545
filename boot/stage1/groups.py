"""groups.py <dtb> -> prints groups.h for the stage1 stub.

The bring-up bisect enables groups of /soc@0 nodes one at a time. Every controllable node carries an explicit
status = "disabled" in the DTB (t545-disable.dtsi); the stub patches that 9-byte value in place to "okay\\0\\0\\0\\0\\0"
(strcmp-compatible) for the groups under test, so a single DTB covers all variants.
"""
import struct
import sys

# (name, [node unit names under /soc@0]) - tested in this order, each on top of everything already known to be good
GROUPS = [
    ("tcsr", ["syscon@1f60000", "hwlock@1f40000"]),
    ("pdc", ["interrupt-controller@b220000", "reset-controller@b2e0000"]),
    ("rsc", ["rsc@179c0000", "mailbox@17990000"]),
    ("noc", ["interconnect@1380000", "interconnect@14e0000", "interconnect@1500000", "interconnect@1620000",
             "interconnect@16e0000", "interconnect@1700000", "interconnect@1740000"]),
    ("noc2", ["interconnect@17900000", "interconnect@17d41000"]),
    ("llcc", ["system-cache-controller@1100000"]),
    ("smmu", ["iommu@15000000"]),
    ("spmi", ["spmi@c440000"]),
    ("usb", ["phy@88e2000", "usb@a6f8800"]),
    ("geni", ["geniqup@8c0000", "geniqup@ac0000", "dma-controller@800000", "dma-controller@a00000"]),
    ("mmc", ["mmc@7c4000"]),
    ("gpu", ["clock-controller@5090000", "iommu@5040000", "gmu@506a000", "gpu@5000000"]),
    ("disp", ["clock-controller@af00000", "display-subsystem@ae00000"]),
    ("video", ["clock-controller@ab00000", "video-codec@aa00000"]),
    ("cam", ["clock-controller@ad00000", "cci@ac4a000", "isp@acb3000"]),
    ("aoss", ["reset-controller@c2a0000", "power-management@c300000"]),
    ("cpufreq", ["cpufreq@17d43000", "lmh@17d70800", "lmh@17d78800"]),
    ("thermal", ["thermal-sensor@c263000", "thermal-sensor@c265000"]),
    ("misc", ["qfprom@784000", "regulator@ff1000"]),
    ("remote", ["remoteproc@8300000", "ipa@1e40000"]),
    ("pinctrl", ["pinctrl@3400000"]),
    ("adsp", ["remoteproc@62400000"]),
    ("wifi", ["remoteproc@4080000", "wifi@18800000"]),
]


def be32(b, o):
    return struct.unpack_from(">I", b, o)[0]


def walk(b):
    assert be32(b, 0) == 0xd00dfeed
    so, ss = be32(b, 8), be32(b, 12)
    p = so
    path = []
    out = {}
    while True:
        t = be32(b, p)
        p += 4
        if t == 1:
            e = b.index(b"\0", p)
            path.append(b[p:e].decode())
            p = (e + 1 + 3) & ~3
        elif t == 2:
            path.pop()
        elif t == 3:
            ln, no = be32(b, p), be32(b, p + 4)
            p += 8
            e = b.index(b"\0", ss + no)
            name = b[ss + no:e].decode()
            out[("/".join(path), name)] = (p, ln)
            p += (ln + 3) & ~3
        elif t == 4:
            pass
        else:
            break
    return out


def main():
    b = open(sys.argv[1], "rb").read()
    props = walk(b)
    offs = []
    starts = [0]
    for name, nodes in GROUPS:
        for n in nodes:
            key = ("/soc@0/" + n, "status")
            key = ("/" + "/soc@0/" + n, "status") if key not in props else key
            cand = [k for k in props if k[1] == "status" and k[0].endswith("soc@0/" + n)]
            assert len(cand) == 1, (n, cand)
            off, ln = props[cand[0]]
            assert ln == 9 and b[off:off + 9] == b"disabled\0", (n, b[off:off + 9])
            offs.append(off)
        starts.append(len(offs))
    bis = [k for k in props if k[1] == "t545,bisect"]
    assert len(bis) == 1, bis
    bis_off = props[bis[0]][0]
    print("/* generated by groups.py - do not edit */")
    prot = [k for k in props if k[1] == "protected-clocks"]
    if prot:
        poff, pln = props[prot[0]]
        print("#define PROT_OFF %#x" % poff)
        print("#define PROT_N %d" % (pln // 4))
    else:
        print("#define PROT_OFF 0")
        print("#define PROT_N 0")
    print("#define NGROUPS %d" % len(GROUPS))
    print("#define BISECT_OFF %#x" % bis_off)
    print("static const char gname[NGROUPS][10] = {%s};" % ",".join('"%s"' % n[:9] for n, _ in GROUPS))
    print("static const unsigned short gstart[NGROUPS + 1] = {%s};" % ",".join(str(s) for s in starts))
    print("static const unsigned int goff[%d] = {%s};" % (len(offs), ",".join("%#x" % o for o in offs)))


main()
